// A C unit's build, as the writers and the checks share it (architecture §6.3, §6.4, §6.6, D21, D65 a, D74 f): what
// agbcc emits for a stub-only `src/<module>.c`, the one encoding of the assembly a generated stub compiles to, so
// the text-layout check lays a C unit out without a compiler and the assemble and link checks build its object with
// binutils alone; the chunk files a C module's stub includes; and the compiler and flags a C module builds with
// (moduleCompile, modules.mk's). The banner each compiler prints is the module's build compiler's
// (core/config/compilers.ts), taken from the compiler a module names, never from a default (architecture-r1-4);
// the C-data ASSERT lines are core/model/c-data-assert.ts's.
//
// Measured (phase 4, p4-c-modules) with pokeemerald's tools/agbcc/bin/agbcc and old_agbcc, both "gcc 2.9-arm-000512",
// over `src/<m>.c` = C_STUB_HEADER and INCLUDE_ASM statements, preprocessed by the host `cc -E -x c -nostdinc -undef
// -I include` and compiled with BUILD_COMPILERS' flags (`-mthumb-interwork -Wimplicit -Wparentheses -O2 -fhex-asm`):
// both compilers print the same text, byte for byte, and only this:
//
//   @ Generated by gcc 2.9-arm-000512 for Thumb/elf
//   \t.code\t16
//   .gcc2_compiled.:
//   \t.include "include/macros.inc"            the header's file-scope asm, then a blank line
//
//   \t.syntax unified                          per INCLUDE_ASM, in source order, then a blank line
//   .include "asm/nonmatchings/<m>/<name>.s"
//   .syntax divided
//
// Every file-scope `asm("<body>")` becomes a tab, its body (which ends with a newline) and a newline. Nothing else:
// no `.text` (the unit stays in `.text`, as `as` starts), no `.align` and nothing appended at the end, so the object's
// `.text` is the chunk files' bytes back to back, assembled from Thumb state (`.code 16`), and its section alignment
// is the larger of 2 (Thumb state) and what the chunk files ask (`.align 2, 0` in thumb_func_start makes it 4): the
// same rule as an asm module's file, whose preamble enters Thumb state too (text-layout's unit alignment, D65 a).
// test/local/c-stub-agbcc.test.ts compiles every emitted stub of two fixtures and klonoa and compares both the text
// and the object's `.text` with this encoding.
import { DIALECT } from '../../foundation/asm/dialect.ts';
import { stubNameOf } from '../../foundation/util/project-files.ts';
import type { Mode } from '../../foundation/rom/span.ts';
import { RomliftInvariantError } from '../../foundation/diagnostics/diagnostic.ts';
import { buildCompilerOf } from '../config/compilers.ts';
import type { BuildCompiler, BuildCompilerId } from '../config/compilers.ts';
import { chunkPathsOf } from './paths.ts';
import type { Model, Module } from './types.ts';

/**
 * The registered build compiler `id`. The config schema refuses an unknown compiler (E_UNKNOWN_COMPILER), so a Model
 * or a build unit naming one is a bug: an invariant error, never a guessed compiler.
 */
function registeredCompiler(id: BuildCompilerId, caller: string): BuildCompiler {
  const compiler = buildCompilerOf(id);
  if (compiler === undefined) throw new RomliftInvariantError(`${caller}: ${id} is no registered build compiler`);
  return compiler;
}

/** The lines a build compiler with banner `banner` prints before the first file-scope `asm` of a unit. */
export function stubUnitPrelude(banner: string): readonly string[] {
  return [`@ Generated by ${banner} for Thumb/elf`, '\t.code\t16', '.gcc2_compiled.:'];
}

/** The state the prelude's `.code 16` puts `as` in before the unit's first statement. */
export const STUB_UNIT_MODE: Mode = 'thumb';

/** What agbcc prints for a file-scope `asm("<body>")`, whose body ends with a newline. */
function fileScopeAsm(body: string): string {
  return `\t${body}\n`;
}

/** The body of INCLUDE_ASM(DIR, NAME) after the preprocessor (foundation/asm/dialect.ts INCLUDE_ASM_HEADER), for the file `<DIR>/<NAME>.s`. */
function includeAsmBody(chunkFile: string): string {
  return `.syntax unified\n.include "${chunkFile}"\n.syntax divided\n`;
}

/**
 * The assembly build compiler `compiler` (a module's, BUILD_COMPILERS) emits for a stub-only `src/<module>.c` whose
 * INCLUDE_ASM statements name `chunkFiles` (`<dir>/<name>.s` each, in source order): the prelude with the compiler's
 * banner, the header's include of the macro file, then one `.include` per statement between `.syntax unified` and
 * `.syntax divided`. An unregistered compiler is an invariant error, as in moduleCompile.
 */
export function stubAssemblyText(chunkFiles: readonly string[], compiler: BuildCompilerId): string {
  const prelude = stubUnitPrelude(registeredCompiler(compiler, 'stubAssemblyText').banner);
  const parts = [`${prelude.join('\n')}\n`, fileScopeAsm(`${DIALECT.macrosInclude}\n`), ...chunkFiles.map((file) => fileScopeAsm(includeAsmBody(file)))];
  return parts.join('');
}

/** The chunk files of a C module, in ROM order: what its generated stub includes (one INCLUDE_ASM each). */
export function stubChunkFiles(model: Pick<Model, 'chunks'>, module: Module): readonly string[] {
  const paths = chunkPathsOf(model);
  const out: string[] = [];
  for (let c = module.chunks.first; c < module.chunks.first + module.chunks.count; c++) {
    const path = paths[c];
    if (path !== undefined) out.push(path);
  }
  return out;
}

/**
 * One chunk of a C module as its stub holds it: `name`, the chunk's (and a C definition's) symbol, and `stub`, the
 * base name of its chunk file, which its INCLUDE_ASM statement names; the two differ for a member of a case-folded
 * group (`<Name>_<ADDR>`, core/model/paths.ts chunkPaths). It mirrors core/reconcile/include-asm.ts WantedChunk,
 * field for field: core/reconcile imports only foundation (architecture §2), so the shape is declared on both sides
 * of that edge.
 */
export interface StubChunk {
  readonly name: string;
  readonly stub: string;
}

/** The chunks of a C module that its stub includes, in ROM order, each with its symbol and its stub name. */
export function stubChunks(model: Pick<Model, 'chunks'>, module: Module): readonly StubChunk[] {
  const paths = chunkPathsOf(model);
  const out: StubChunk[] = [];
  for (let c = module.chunks.first; c < module.chunks.first + module.chunks.count; c++) {
    const path = paths[c];
    const chunk = model.chunks[c];
    if (path !== undefined && chunk !== undefined) out.push({ name: chunk.name, stub: stubNameOf(path) });
  }
  return out;
}

/** The assembly the module's build compiler emits for the generated stub of C module `module` (stubAssemblyText over its chunk files). */
export function stubUnitAssembly(model: Pick<Model, 'chunks'>, module: Module): string {
  return stubAssemblyText(stubChunkFiles(model, module), module.compiler);
}

/**
 * The cc1 and the flags a C module compiles with: its build compiler's cc1 (BUILD_COMPILERS) and the Model's cflags,
 * which modules.ts builds as the compiler's default flags followed by the module's `cflags`.
 */
export function moduleCompile(module: Pick<Module, 'compiler' | 'cflags'>): { readonly cc1: string; readonly flags: readonly string[] } {
  const compiler = registeredCompiler(module.compiler, 'moduleCompile');
  return { cc1: compiler.cc1, flags: module.cflags };
}
