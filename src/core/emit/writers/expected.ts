// The `expected` writer (architecture §6.1 rung 3, §6.3, §6.8, D92, D101 a): objdiff's target of every generated module
// with chunks. Scope: module; ownership generated.
//
//   expected/<module>.s       the module as its build unit assembles it: for a `c` module agbcc's output of the
//                             stub-only src/<module>.c (core/model/c-unit.ts stubAssemblyText, the one encoding of
//                             that text) over the chunk files in ROM order, each at the path the tree writes it (its
//                             asm/matchings twin for a function the C defines, unit-text.ts writtenChunkPath); for an
//                             asm or data module one `.include` of its own source.
//
// `make expected` (the scaffold's Makefile) assembles it, as it is, into build/expected/<module>.o (paths.ts
// expectedObjectPath): the build object's symbols, mapping symbols, relocations and bytes while every function is
// INCLUDE_ASM, so objdiff scores every function of an untouched project at 100%, and keeps that target whatever is
// decompiled later. g6.expected-bytes links it at its module's address and judges it by the ROM range. A module's
// data range (§6.6) is not part of it: its bytes are the C object's `.rodata`.
import type { Rom } from '../../../foundation/rom/rom.ts';
import { hex } from '../../../foundation/util/hex.ts';
import { stubAssemblyText } from '../../model/c-unit.ts';
import { expectedSourcePath, hasExpectedTarget, moduleSource } from '../../model/paths.ts';
import type { Model, Module } from '../../model/types.ts';
import type { EmitContext, FileEntry, Writer } from '../tree.ts';
import { writtenChunkPath } from '../unit-text.ts';

/** The comment line that opens the file of `module`. */
function heading(path: string, module: Module, what: string): string {
  return `@ ${path}: module ${module.name} (0x${hex(module.span.start)}..0x${hex(module.span.end)}) ${what}; generated by romlift.`;
}

/** The text of expected/<module>.s (see the header). */
export function expectedText(model: Model, cx: EmitContext, module: Module): string {
  const path = expectedSourcePath(module.name);
  if (module.kind !== 'c') return `${heading(path, module, "as its unit assembles it, objdiff's target")}\n.include "${moduleSource(model, module)}"\n`;
  const chunks: string[] = [];
  for (let c = module.chunks.first; c < module.chunks.first + module.chunks.count; c++) {
    const chunk = writtenChunkPath(model, cx, module, c);
    if (chunk !== undefined) chunks.push(chunk);
  }
  return `${heading(path, module, "as its C unit assembles while every function is INCLUDE_ASM, objdiff's target")}\n${stubAssemblyText(chunks, module.compiler)}`;
}

function* expectedFiles(_rom: Rom, model: Model, cx: EmitContext, module: number | null): Iterable<FileEntry> {
  const m = module === null ? undefined : model.modules[module];
  if (m === undefined || !hasExpectedTarget(m)) return;
  yield { ownership: 'generated', path: expectedSourcePath(m.name), text: expectedText(model, cx, m), writer: 'expected' };
}

export const expectedWriter: Writer = {
  id: 'expected',
  scope: 'module',
  emit: expectedFiles,
};
