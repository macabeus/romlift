// The `symbols` writer (architecture §6.3): symbols.ld, the RAM and absolute symbols. Scope: global.
//
// One `name = 0xADDR;` line for every Model.symbols entry outside the ROM ([0x08000000, ROM end)), sorted by
// address, then name (code units); a symbol inside the ROM is a label of the file that holds its bytes.
// The file is always written, with a comment line even when no symbol lies outside the ROM, so the tree
// keeps one shape whatever the TOML holds; ldscript.txt INCLUDEs it only when it defines a symbol
// (ldscript.ts), so the link never reads a file it does not need.
import type { Rom } from '../../../foundation/rom/rom.ts';
import { hexAddr } from '../../../foundation/util/hex.ts';
import { SYMBOLS_PATH } from '../../model/paths.ts';
import { externalSymbols } from '../../model/symbols.ts';
import type { Model } from '../../model/types.ts';
import type { FileEntry, Writer } from '../tree.ts';

/** The text of symbols.ld. */
function symbolsText(model: Pick<Model, 'symbols' | 'rom'>): string {
  const lines = externalSymbols(model).map((s) => `${s.name} = ${hexAddr(s.addr)};`);
  return `/* ${SYMBOLS_PATH}: the RAM and absolute symbols, generated by romlift; edit [symbols] in the TOML instead. */\n${lines.map((l) => `${l}\n`).join('')}`;
}

export const symbolsWriter: Writer = {
  id: 'symbols',
  scope: 'global',
  emit(_rom: Rom, model: Model): Iterable<FileEntry> {
    return [{ ownership: 'generated', path: SYMBOLS_PATH, text: symbolsText(model), writer: 'symbols' }];
  },
};
