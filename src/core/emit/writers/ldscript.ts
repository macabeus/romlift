// The `ldscript` writer (architecture §6.3, §6.7, D46): ldscript.txt, the link order. Scope: global.
//
//   INCLUDE symbols.ld                         only when symbols.ld defines a symbol (symbols.ts)
//   SECTIONS {
//       . = 0x08000000;
//       .text : {
//           build/<module>.o(.text);           one line per build unit (paths.ts buildUnits), in ROM order
//       }
//       .<module> <runAt> : AT(<load>) {       a runs_at module: linked at its run address, loaded in place
//           build/<module>.o(.text);
//       }
//       __load_<module> = LOADADDR(.<module>);
//       .text.<module> <load> : AT(<load>) {   the units after a runs_at module, from the first one's start
//           ...
//       }
//   }
//
// Every byte of the ROM is in exactly one unit and the units follow each other without a gap, so
// `objcopy -O binary` writes the ROM: from the lowest load address to the highest, nothing past the ROM end.
// A section after a runs_at one names its load address because the location counter is then in run space.
// The ROM-order units of phase 3 are asm and data objects, which hold only .text; C data is phase 4's (D21).
import type { Rom } from '../../../foundation/rom/rom.ts';
import { ROM_BASE } from '../../../foundation/rom/rom.ts';
import { hexAddr } from '../../../foundation/util/hex.ts';
import { buildUnits, LDSCRIPT_PATH, SYMBOLS_PATH } from '../../model/paths.ts';
import type { Model, Module } from '../../model/types.ts';
import type { FileEntry, Writer } from '../tree.ts';
import { externalSymbols } from './symbols.ts';

const INDENT = '    ';

/** The text of ldscript.txt. */
export function ldscriptText(model: Pick<Model, 'modules' | 'chunks' | 'symbols' | 'rom'>): string {
  const units = buildUnits(model);
  const lines: string[] = [`/* ${LDSCRIPT_PATH}: the build units in ROM order, generated by romlift. */`];
  if (externalSymbols(model).length > 0) lines.push(`INCLUDE ${SYMBOLS_PATH}`);
  lines.push('SECTIONS {', `${INDENT}. = ${hexAddr(ROM_BASE)};`);
  let open = false;
  let afterRunAt = false;
  const close = (): void => {
    if (open) lines.push(`${INDENT}}`);
    open = false;
  };
  model.modules.forEach((module: Module, i) => {
    const object = units[i]?.object ?? '';
    if (module.runAt !== undefined) {
      close();
      lines.push(`${INDENT}.${module.name} ${hexAddr(module.runAt)} : AT(${hexAddr(module.span.start)}) {`, `${INDENT}${INDENT}${object}(.text);`, `${INDENT}}`);
      lines.push(`${INDENT}__load_${module.name} = LOADADDR(.${module.name});`);
      afterRunAt = true;
      return;
    }
    if (!open) {
      const load = hexAddr(module.span.start);
      lines.push(afterRunAt ? `${INDENT}.text.${module.name} ${load} : AT(${load}) {` : `${INDENT}.text : {`);
      open = true;
    }
    lines.push(`${INDENT}${INDENT}${object}(.text);`);
  });
  close();
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

export const ldscriptWriter: Writer = {
  id: 'ldscript',
  scope: 'global',
  emit(_rom: Rom, model: Model): Iterable<FileEntry> {
    return [{ ownership: 'generated', path: LDSCRIPT_PATH, text: ldscriptText(model), writer: 'ldscript' }];
  },
};
