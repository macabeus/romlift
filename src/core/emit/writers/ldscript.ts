// The `ldscript` writer (architecture §6.3, §6.6, §6.7, D46): ldscript.txt, the link order. Scope: global.
//
//   INCLUDE symbols.ld                         only when symbols.ld defines a symbol (symbols.ts)
//   SECTIONS {
//       . = 0x08000000;
//       .text : {
//           build/<module>.o(.text);           one line per build unit (paths.ts buildUnits), in ROM order
//       }
//       .<module> <runAt> : AT(<load>) {       a runs_at module: linked at its run address, loaded in place
//           build/<module>.o(.text);
//       }
//       __load_<module> = LOADADDR(.<module>);
//       .text.<module> <load> : AT(<load>) {   the units after a runs_at module or a data range, from the first one's start
//           ...
//       }
//       .rodata_<m> <start> : AT(<start>) { build/src/<m>.o(.rodata .rodata.*) }    a C data range, in ROM order (phase 6)
//       ASSERT(SIZEOF(.rodata_<m>) == <size>, "src/<m>.c's read-only data is not the <size> bytes of its data range [a, b); see AGENTS.md")
//       .c_data_<m> (NOLOAD) : { *src/<m>.o(.rodata* .data* .bss* COMMON) }     per C unit, in ROM order (D21, D74 f)
//       ASSERT(SIZEOF(.c_data_<m>) == 0, "src/<m>.c defines data; see AGENTS.md (only read-only data is placed, in a data range: data_start)")
//   }
//
// Every byte of the ROM is in exactly one unit or data range and they follow each other without a gap, so
// `objcopy -O binary` writes the ROM: from the lowest load address to the highest, nothing past the ROM end.
// A section after a runs_at one names its load address because the location counter is then in run space; one after a
// data range names it too, so its place never depends on the size the range's ASSERT checks.
// Asm and data objects hold only .text. A C unit's object (build/src/<m>.o) has only its .text placed, and, when its
// module has a data range (core/model/c-data-assert.ts, architecture §6.6, D92), its `.rodata` at that range; every
// other section it has goes into its NOLOAD check section (with a data range, its `.data*`, `.bss*` and COMMON only),
// which the ASSERT requires to be empty, so a C file that defines data outside a data range fails the link with a
// message naming it (architecture §6.6, D21). The check sections hold nothing in a linking tree and NOLOAD loads
// nothing, so the image is the units' .text and the data ranges' .rodata.
import type { Rom } from '../../../foundation/rom/rom.ts';
import { ROM_BASE } from '../../../foundation/rom/rom.ts';
import { hexAddr } from '../../../foundation/util/hex.ts';
import { isCSource } from '../../../foundation/util/project-files.ts';
import {
  cDataAssertLine,
  cDataSectionLine,
  cRamDataSectionLine,
  cRodataAssertLine,
  cRodataSectionLine,
} from '../../model/c-data-assert.ts';
import { ROM_SECTION, loadSymbolOf, modulePieces, runSectionOf } from '../../model/modules.ts';
import { LDSCRIPT_PATH, SYMBOLS_PATH, buildUnits } from '../../model/paths.ts';
import { externalSymbols } from '../../model/symbols.ts';
import type { Model } from '../../model/types.ts';
import type { FileEntry, Writer } from '../tree.ts';

const INDENT = '    ';

/** The text of ldscript.txt. */
export function ldscriptText(model: Pick<Model, 'modules' | 'chunks' | 'symbols' | 'rom' | 'labels'>): string {
  const units = buildUnits(model);
  const lines: string[] = [`/* ${LDSCRIPT_PATH}: the build units in ROM order, generated by romlift. */`];
  if (externalSymbols(model).length > 0) lines.push(`INCLUDE ${SYMBOLS_PATH}`);
  lines.push('SECTIONS {', `${INDENT}. = ${hexAddr(ROM_BASE)};`);
  let open = false;
  let placed = false;
  const close = (): void => {
    if (open) lines.push(`${INDENT}}`);
    open = false;
  };
  for (const piece of modulePieces(model.modules)) {
    const module = model.modules[piece.module];
    const object = units[piece.module]?.object ?? '';
    if (module === undefined) continue;
    if (piece.part === 'data') {
      close();
      lines.push(
        `${INDENT}${cRodataSectionLine(module.name, object, piece.span)}`,
        `${INDENT}${cRodataAssertLine(module.name, piece.span)}`,
      );
      placed = true;
      continue;
    }
    if (module.runAt !== undefined) {
      close();
      lines.push(
        `${INDENT}${runSectionOf(module)} ${hexAddr(module.runAt)} : AT(${hexAddr(module.span.start)}) {`,
        `${INDENT}${INDENT}${object}(.text);`,
        `${INDENT}}`,
      );
      lines.push(`${INDENT}${loadSymbolOf(module)} = LOADADDR(${runSectionOf(module)});`);
      placed = true;
      continue;
    }
    if (!open) {
      const load = hexAddr(module.span.start);
      lines.push(
        placed ? `${INDENT}${ROM_SECTION}.${module.name} ${load} : AT(${load}) {` : `${INDENT}${ROM_SECTION} : {`,
      );
      open = true;
    }
    lines.push(`${INDENT}${INDENT}${object}(.text);`);
  }
  close();
  model.modules.forEach((module, i) => {
    if (!isCSource(units[i]?.source ?? '')) return;
    lines.push(
      `${INDENT}${module.dataRange === undefined ? cDataSectionLine(module.name) : cRamDataSectionLine(module.name)}`,
      `${INDENT}${cDataAssertLine(module.name)}`,
    );
  });
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

export const ldscriptWriter: Writer = {
  id: 'ldscript',
  scope: 'global',
  emit(_rom: Rom, model: Model): Iterable<FileEntry> {
    return [{ ownership: 'generated', path: LDSCRIPT_PATH, text: ldscriptText(model), writer: 'ldscript' }];
  },
};
