// The C unit's build as writers and checks share it (core/model/c-unit.ts, D74 f): the assembly agbcc and old_agbcc
// emit for a stub-only src/<m>.c, as measured (test/local/c-stub-agbcc.test.ts proves it against the compilers), the
// INCLUDE_ASM expansion it rests on, the cc1 and flags of a C module, and the two ldscript lines of the C-data check.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { RomliftInvariantError } from '../../../src/foundation/diagnostics/diagnostic.ts';
import { cDataAssertLine, cDataSectionLine } from '../../../src/core/model/c-data-assert.ts';
import {
  moduleCompile,
  STUB_UNIT_MODE,
  stubAssemblyText,
  stubChunkFiles,
  stubChunks,
  stubUnitAssembly,
  stubUnitPrelude,
} from '../../../src/core/model/c-unit.ts';
import { BUILD_COMPILERS } from '../../../src/core/config/compilers.ts';
import { DIALECT, INCLUDE_ASM_HEADER } from '../../../src/foundation/asm/dialect.ts';
import { dataItem, modelOf, romWith } from '../../helpers/model.ts';

/** What pokeemerald's agbcc and old_agbcc printed for `#include "include_asm.h"` and INCLUDE_ASM of f1 and f2 (phase 4). */
const MEASURED = [
  '@ Generated by gcc 2.9-arm-000512 for Thumb/elf',
  '\t.code\t16',
  '.gcc2_compiled.:',
  '\t.include "include/macros.inc"',
  '',
  '\t.syntax unified',
  '.include "asm/nonmatchings/main/f1.s"',
  '.syntax divided',
  '',
  '\t.syntax unified',
  '.include "asm/nonmatchings/main/f2.s"',
  '.syntax divided',
  '',
  '',
].join('\n');

test('the stub assembly is what agbcc and old_agbcc printed, byte for byte, and only the prelude for a unit without statements', () => {
  for (const compiler of ['agbcc', 'old_agbcc']) {
    assert.equal(stubAssemblyText(['asm/nonmatchings/main/f1.s', 'asm/nonmatchings/main/f2.s'], compiler), MEASURED, compiler);
    const prelude = stubUnitPrelude(BUILD_COMPILERS[compiler]?.banner ?? 'unregistered');
    assert.equal(stubAssemblyText([], compiler), `${prelude.join('\n')}\n\t${DIALECT.macrosInclude}\n\n`, compiler);
    assert.ok(prelude.includes('\t.code\t16'));
  }
  assert.equal(STUB_UNIT_MODE, 'thumb', '`.code 16`');
});

test('the stub assembly carries the banner of the compiler it is given; an unregistered one is an invariant error (architecture-r1-4)', () => {
  assert.equal(stubUnitPrelude('gcc 9.9-test')[0], '@ Generated by gcc 9.9-test for Thumb/elf');
  assert.throws(() => stubAssemblyText([], 'mycc'), RomliftInvariantError, 'the schema refuses an unknown compiler (E_UNKNOWN_COMPILER)');
  assert.throws(() => stubAssemblyText([], ''), RomliftInvariantError);
});

test('the expansion it encodes is include_asm.h\'s: INCLUDE_ASM and the file-scope include of the macro file', () => {
  assert.ok(INCLUDE_ASM_HEADER.includes('#define INCLUDE_ASM(DIR, NAME) asm(".syntax unified\\n.include \\"" DIR "/" #NAME ".s\\"\\n.syntax divided\\n")'));
  assert.ok(INCLUDE_ASM_HEADER.includes(`asm("${DIALECT.macrosInclude.replace(/"/g, '\\"')}\\n");`));
});

test('a module\'s stub chunk files and names, and its assembly', () => {
  const rom = romWith([], { size: 0x200 });
  const model = modelOf(rom, {
    modules: [
      { name: 'rom_header', chunks: [{ kind: 'header', name: 'rom_header', items: [dataItem(0x0800_0000, 0xc0)] }] },
      { name: 'main', kind: 'c', chunks: [{ name: 'VBlankCB', items: [dataItem(0x0800_00c0, 0x20)] }, { name: 'VblankCB', items: [dataItem(0x0800_00e0, 0x20)] }, { kind: 'orphan', name: 'unk_08000100', items: [dataItem(0x0800_0100, 0x100)] }] },
    ],
  });
  const main = model.modules[1]!;
  const files = stubChunkFiles(model, main);
  assert.deepEqual(files, ['asm/nonmatchings/main/VBlankCB_080000C0.s', 'asm/nonmatchings/main/VblankCB_080000E0.s', 'asm/nonmatchings/main/unk_08000100.s']);
  assert.deepEqual(stubChunks(model, main), [
    { name: 'VBlankCB', stub: 'VBlankCB_080000C0' },
    { name: 'VblankCB', stub: 'VblankCB_080000E0' },
    { name: 'unk_08000100', stub: 'unk_08000100' },
  ]);
  assert.equal(stubUnitAssembly(model, main), stubAssemblyText(files, main.compiler));
  assert.equal(stubUnitAssembly(model, { ...main, compiler: 'old_agbcc' }), stubAssemblyText(files, 'old_agbcc'), 'the module\'s compiler');
  assert.throws(() => stubUnitAssembly(model, { ...main, compiler: 'mycc' }), RomliftInvariantError, 'a module naming no registered compiler');
});

test('a C module compiles with its compiler\'s cc1 and the Model\'s flags', () => {
  assert.deepEqual(moduleCompile({ compiler: 'old_agbcc', cflags: ['-O2', '-g'] }), { cc1: 'tools/agbcc/bin/old_agbcc', flags: ['-O2', '-g'] });
  assert.deepEqual(moduleCompile({ compiler: 'agbcc', cflags: [] }), { cc1: 'tools/agbcc/bin/agbcc', flags: [] });
  assert.throws(() => moduleCompile({ compiler: 'mycc', cflags: [] }), RomliftInvariantError, 'the schema refuses an unknown compiler (E_UNKNOWN_COMPILER)');
});

test('the C-data check lines are the frozen text (D74 f, architecture §6.6)', () => {
  assert.equal(cDataSectionLine('main'), '.c_data_main (NOLOAD) : { *src/main.o(.rodata* .data* .bss* COMMON) }');
  assert.equal(cDataAssertLine('main'), 'ASSERT(SIZEOF(.c_data_main) == 0, "src/main.c defines data; see AGENTS.md (only read-only data is placed, in a data range: data_start)")');
});
