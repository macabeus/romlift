// The `ldscript` writer (architecture §6.3, §6.6, §6.7, D46, D92): ldscript.txt names every build unit once in ROM
// order; a runs_at module gets its own section at its run address, loaded in place, with __load_<module>;
// the units after it open a section at their load address; INCLUDE symbols.ld only when it defines a symbol; a C
// data range places its C object's `.rodata` at the range, in ROM order, with an ASSERT of its size.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { ldscriptText, ldscriptWriter } from '../../../../src/core/emit/writers/ldscript.ts';
import type { Model } from '../../../../src/core/model/types.ts';
import { entryDiagnostics } from '../../../helpers/text-layout.ts';
import { dataItem, modelOf, romWith } from '../../../helpers/model.ts';

const CX = { decomp: { defined: [] } };
const rom = romWith([], { size: 0x400 });

function plain(symbols: Model['symbols'] = []): Model {
  return modelOf(rom, {
    modules: [
      { name: 'rom_header', chunks: [{ kind: 'header', name: 'rom_header', items: [dataItem(0x0800_0000, 0xc0)] }] },
      { name: 'crt0', chunks: [{ kind: 'startup', name: 'start', mode: 'arm', items: [dataItem(0x0800_00c0, 0x40)] }] },
      { name: 'main', chunks: [{ name: 'Func', items: [dataItem(0x0800_0100, 0x100)] }] },
      { name: 'data', kind: 'data', chunks: [{ kind: 'data', name: 'data', items: [dataItem(0x0800_0200, 0x200)] }] },
    ],
    symbols,
  });
}

test('the units in ROM order in one .text section; no INCLUDE without symbols outside the ROM', () => {
  const model = plain([{ addr: 0x0800_0200, name: 'gInRom' }]);
  const [e] = [...ldscriptWriter.emit(rom, model, CX, null)];
  assert.ok(e !== undefined && e.ownership === 'generated');
  assert.equal(e.path, 'ldscript.txt');
  assert.equal(e.writer, 'ldscript');
  assert.equal(
    e.text,
    `/* ldscript.txt: the build units in ROM order, generated by romlift. */
SECTIONS {
    . = 0x08000000;
    .text : {
        build/rom_header.o(.text);
        build/crt0.o(.text);
        build/main.o(.text);
        build/data.o(.text);
    }
}
`,
  );
  assert.deepEqual(entryDiagnostics(rom, model, e), []);
});

test('INCLUDE symbols.ld when a symbol lies outside the ROM', () => {
  const model = plain([{ addr: 0x0300_0000, name: 'gRam' }]);
  assert.match(ldscriptText(model), /^\/\*.*\*\/\nINCLUDE symbols\.ld\nSECTIONS \{\n/);
});

test('a runs_at module: its own section at the run address, AT its load address, __load_ symbol, then the rest at their load address', () => {
  const model = modelOf(rom, {
    modules: [
      { name: 'rom_header', chunks: [{ kind: 'header', name: 'rom_header', items: [dataItem(0x0800_0000, 0xc0)] }] },
      { name: 'main', chunks: [{ name: 'Func', items: [dataItem(0x0800_00c0, 0x40)] }] },
      { name: 'sound_ram', runAt: 0x0300_0388, chunks: [{ name: 'SoundMain', runAt: 0x0300_0388, items: [dataItem(0x0800_0100, 0x80)] }] },
      { name: 'main_2', chunks: [{ name: 'Other', items: [dataItem(0x0800_0180, 0x80)] }] },
      { name: 'data', kind: 'data', chunks: [{ kind: 'data', name: 'data', items: [dataItem(0x0800_0200, 0x200)] }] },
    ],
  });
  const text = ldscriptText(model);
  assert.equal(
    text,
    `/* ldscript.txt: the build units in ROM order, generated by romlift. */
SECTIONS {
    . = 0x08000000;
    .text : {
        build/rom_header.o(.text);
        build/main.o(.text);
    }
    .sound_ram 0x03000388 : AT(0x08000100) {
        build/sound_ram.o(.text);
    }
    __load_sound_ram = LOADADDR(.sound_ram);
    .text.main_2 0x08000180 : AT(0x08000180) {
        build/main_2.o(.text);
        build/data.o(.text);
    }
}
`,
  );
  const [e] = [...ldscriptWriter.emit(rom, model, CX, null)];
  assert.ok(e !== undefined);
  assert.deepEqual(entryDiagnostics(rom, model, e), []);
});

test('a C unit: its object build/src/<m>.o places only .text, then its C-data check section and ASSERT, in ROM order (D74 f)', () => {
  const model = modelOf(rom, {
    modules: [
      { name: 'rom_header', chunks: [{ kind: 'header', name: 'rom_header', items: [dataItem(0x0800_0000, 0xc0)] }] },
      { name: 'main', kind: 'c', chunks: [{ name: 'Func', items: [dataItem(0x0800_00c0, 0x40)] }] },
      { name: 'sound_ram', runAt: 0x0300_0388, chunks: [{ name: 'SoundMain', runAt: 0x0300_0388, items: [dataItem(0x0800_0100, 0x80)] }] },
      { name: 'main_2', kind: 'c', chunks: [{ name: 'Other', items: [dataItem(0x0800_0180, 0x80)] }] },
      { name: 'data', kind: 'data', chunks: [{ kind: 'data', name: 'data', items: [dataItem(0x0800_0200, 0x200)] }] },
    ],
  });
  assert.equal(
    ldscriptText(model),
    `/* ldscript.txt: the build units in ROM order, generated by romlift. */
SECTIONS {
    . = 0x08000000;
    .text : {
        build/rom_header.o(.text);
        build/src/main.o(.text);
    }
    .sound_ram 0x03000388 : AT(0x08000100) {
        build/sound_ram.o(.text);
    }
    __load_sound_ram = LOADADDR(.sound_ram);
    .text.main_2 0x08000180 : AT(0x08000180) {
        build/src/main_2.o(.text);
        build/data.o(.text);
    }
    .c_data_main (NOLOAD) : { *src/main.o(.rodata* .data* .bss* COMMON) }
    ASSERT(SIZEOF(.c_data_main) == 0, "src/main.c defines data; see AGENTS.md (romlift does not place C data yet)")
    .c_data_main_2 (NOLOAD) : { *src/main_2.o(.rodata* .data* .bss* COMMON) }
    ASSERT(SIZEOF(.c_data_main_2) == 0, "src/main_2.c defines data; see AGENTS.md (romlift does not place C data yet)")
}
`,
  );
  const [e] = [...ldscriptWriter.emit(rom, model, CX, null)];
  assert.ok(e !== undefined);
  assert.deepEqual(entryDiagnostics(rom, model, e), []);
});

test('a C data range (phase 6): `.rodata_<m>` at its start, in ROM order, its ASSERT, the next unit at its load address; its check section keeps RAM data only', () => {
  const base = modelOf(rom, {
    modules: [
      { name: 'rom_header', chunks: [{ kind: 'header', name: 'rom_header', items: [dataItem(0x0800_0000, 0xc0)] }] },
      { name: 'main', kind: 'c', chunks: [{ name: 'F', items: [dataItem(0x0800_00c0, 0x140)] }] },
      { name: 'data', kind: 'data', chunks: [{ kind: 'data', name: 'data', items: [dataItem(0x0800_0200, 0x80)] }] },
      { name: 'tail', kind: 'data', chunks: [{ kind: 'data', name: 'tail', items: [dataItem(0x0800_0280, 0x80)] }] },
      { name: 'end', kind: 'data', chunks: [{ kind: 'data', name: 'end', items: [dataItem(0x0800_0300, 0x100)] }] },
    ],
  });
  // main's range is [0x08000280, 0x08000300), where `tail` stood: the modules the model keeps and main's range.
  const model: Model = {
    ...base,
    modules: base.modules.filter((m) => m.name !== 'tail').map((m) => (m.name === 'main' ? { ...m, dataRange: { start: 0x0800_0280, end: 0x0800_0300 } } : m)),
  };
  assert.equal(
    ldscriptText(model),
    `/* ldscript.txt: the build units in ROM order, generated by romlift. */
SECTIONS {
    . = 0x08000000;
    .text : {
        build/rom_header.o(.text);
        build/src/main.o(.text);
        build/data.o(.text);
    }
    .rodata_main 0x08000280 : AT(0x08000280) { build/src/main.o(.rodata .rodata.*) }
    ASSERT(SIZEOF(.rodata_main) == 128, "src/main.c's read-only data is not the 128 bytes of its data range [0x08000280, 0x08000300); see AGENTS.md")
    .text.end 0x08000300 : AT(0x08000300) {
        build/end.o(.text);
    }
    .c_data_main (NOLOAD) : { *src/main.o(.data* .bss* COMMON) }
    ASSERT(SIZEOF(.c_data_main) == 0, "src/main.c defines data; see AGENTS.md (romlift does not place C data yet)")
}
`,
  );
  const [e] = [...ldscriptWriter.emit(rom, model, CX, null)];
  assert.ok(e !== undefined);
  assert.deepEqual(entryDiagnostics(rom, model, e), []);
});
