// The `symbols` writer (architecture §6.3): symbols.ld defines every [symbols] entry outside the ROM, by
// address then name; it is written even when it defines nothing.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { symbolsWriter } from '../../../../src/core/emit/writers/symbols.ts';
import { externalSymbols } from '../../../../src/core/model/symbols.ts';
import type { Model } from '../../../../src/core/model/types.ts';
import { checkEntry } from '../../../../src/core/verify/text-layout.ts';
import { dataItem, modelOf, romWith } from '../../../helpers/model.ts';

const CX = { decomp: { defined: new Set<string>() } };
const rom = romWith([], { size: 0x400 });

function withSymbols(symbols: Model['symbols']): Model {
  return modelOf(rom, { modules: [{ name: 'data', kind: 'data', chunks: [{ kind: 'data', name: 'data', items: [dataItem(0x0800_0000, 0x400)] }] }], symbols });
}

test('symbols outside the ROM, by address then name; ROM symbols are left to their files', () => {
  const model = withSymbols([
    { addr: 0x0300_0010, name: 'gB' },
    { addr: 0x0800_0100, name: 'gInRom' },
    { addr: 0x0200_0000, name: 'gZ' },
    { addr: 0x0300_0010, name: 'gA' },
    { addr: 0x0800_0400, name: 'gPastEnd' },
    { addr: 0x0400_0000, name: 'REG_DISPCNT' },
  ]);
  assert.deepEqual(
    externalSymbols(model).map((s) => s.name),
    ['gZ', 'gA', 'gB', 'REG_DISPCNT', 'gPastEnd'],
  );
  const [e] = [...symbolsWriter.emit(rom, model, CX, null)];
  assert.ok(e !== undefined && e.ownership === 'generated');
  assert.equal(e.path, 'symbols.ld');
  assert.equal(e.writer, 'symbols');
  assert.equal(
    e.text,
    `/* symbols.ld: the RAM and absolute symbols, generated by romlift; edit [symbols] in the TOML instead. */
gZ = 0x02000000;
gA = 0x03000010;
gB = 0x03000010;
REG_DISPCNT = 0x04000000;
gPastEnd = 0x08000400;
`,
  );
  assert.deepEqual(checkEntry(rom, model, e), []);
});

test('with no symbol outside the ROM the file is still written, a comment only', () => {
  const model = withSymbols([{ addr: 0x0800_0010, name: 'gInRom' }]);
  const [e] = [...symbolsWriter.emit(rom, model, CX, null)];
  assert.ok(e !== undefined && e.ownership === 'generated');
  assert.equal(e.text, '/* symbols.ld: the RAM and absolute symbols, generated by romlift; edit [symbols] in the TOML instead. */\n');
  assert.deepEqual(checkEntry(rom, model, e), []);
});
