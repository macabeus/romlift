// The modules-mk writer (architecture §6.3, D47, D74 f): modules.mk holds OBJS (every unit's object in link order),
// C_OBJS (the C units'), and per C object its CC1 and CFLAGS as target-specific variables, each line naming
// build/src/<module>.o, with the module's compiler and the Model's flags (the compiler's, then the module's cflags);
// from phase 6 EXPECTED_OBJS, every generated module's objdiff target (build/expected/<module>.o, `make expected`, D92, D101 c);
// with C units, the warning for an INCLUDE_ASM restored by hand over a decompiled function's moved file (D111).
// and `make debug` (D124): the ELF with debug information, each C unit compiled again with -g into build/debug/src/.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { modulesMkText, modulesMkWriter } from '../../../../src/core/emit/writers/modules-mk.ts';
import { buildModel } from '../../../../src/core/model/model.ts';
import { dataItem, modelOf, romWith } from '../../../helpers/model.ts';
import { BASE, HEADER_END, analysisOf, configOf, fact } from '../../layout/hand-made.ts';

const CX = { decomp: { defined: [] } };

/** `make debug` as modules.mk writes it (D124) for the debug objects `objects`, before the C units' own rules. */
function debugHead(objects: readonly string[]): string {
  return `# make debug: the ELF with DWARF debug information for the C modules, its bytes checked against the ROM (D124).
DEBUG_OBJS := $(patsubst build/src/%.o,build/debug/src/%.o,$(OBJS))
.PHONY: debug
debug: build/debug/$(NAME).elf
build/debug/$(NAME).elf: $(ROM)${objects.map((o) => ` ${o}`).join('')} FORCE
\t@mkdir -p $(@D)
\tsed 's|build/src/|build/debug/src/|g' ldscript.txt > build/debug/ldscript.txt
\t$(LD) -T build/debug/ldscript.txt -o $@ $(DEBUG_OBJS)
\t$(OBJCOPY) -O binary $@ build/debug/$(NAME).gba
\t@cmp build/debug/$(NAME).gba $(ROM) || { echo "$@: its bytes are not $(ROM)'s, so its addresses are not the ROM's (-g changed the code a compiler wrote)" >&2; rm -f $@; exit 1; }
`;
}
const rom = romWith([], { size: 0x400 });

test("OBJS, C_OBJS and each C object's compiler and flags, in link order", () => {
  const model = modelOf(rom, {
    modules: [
      { name: 'rom_header', chunks: [{ kind: 'header', name: 'rom_header', items: [dataItem(0x0800_0000, 0xc0)] }] },
      { name: 'main', kind: 'c', chunks: [{ name: 'F', items: [dataItem(0x0800_00c0, 0x40)] }] },
      {
        name: 'm4a',
        library: { name: 'm4a', version: '2001' },
        chunks: [{ name: 'SoundMain', items: [dataItem(0x0800_0100, 0x40)] }],
      },
      {
        name: 'old',
        kind: 'c',
        compiler: 'old_agbcc',
        cflags: ['-O1', '-g'],
        chunks: [{ name: 'G', items: [dataItem(0x0800_0140, 0xc0)] }],
      },
      { name: 'data', kind: 'data', chunks: [{ kind: 'data', name: 'data', items: [dataItem(0x0800_0200, 0x200)] }] },
    ],
  });
  const [e] = [...modulesMkWriter.emit(rom, model, CX, null)];
  assert.deepEqual(e, {
    ownership: 'generated',
    path: 'modules.mk',
    writer: 'modules-mk',
    text: `# modules.mk: the build units in link order and each C unit's compiler, generated by romlift.
OBJS := \\
\tbuild/rom_header.o \\
\tbuild/src/main.o \\
\tbuild/m4a.o \\
\tbuild/src/old.o \\
\tbuild/data.o
C_OBJS := \\
\tbuild/src/main.o \\
\tbuild/src/old.o
EXPECTED_OBJS := \\
\tbuild/expected/rom_header.o \\
\tbuild/expected/main.o \\
\tbuild/expected/m4a.o \\
\tbuild/expected/old.o \\
\tbuild/expected/data.o
build/src/main.o: CC1 := tools/agbcc/bin/agbcc
build/src/main.o: CFLAGS :=
build/src/old.o: CC1 := tools/agbcc/bin/old_agbcc
build/src/old.o: CFLAGS := -O1 -g
# A stub put back by hand for a function the C defined: its file is under asm/matchings/ until generate runs (D111).
ROMLIFT_RESTORED := $(strip $(foreach f,$(shell sed -n 's|^[[:space:]]*INCLUDE_ASM("\\([^"]*\\)",[[:space:]]*\\([A-Za-z0-9_]*\\)).*|\\1/\\2.s|p' src/main.c src/old.c 2>/dev/null),$(if $(wildcard $(f)),,$(if $(wildcard $(subst asm/nonmatchings/,asm/matchings/,$(f))),$(f)))))
ifneq ($(ROMLIFT_RESTORED),)
$(warning INCLUDE_ASM names $(ROMLIFT_RESTORED), which generate moved to asm/matchings/ when the C defined the function: run $(or $(ROMLIFT_RUN),npx romlift) generate to write it back)
endif
${debugHead(['build/debug/src/main.o', 'build/debug/src/old.o'])}build/debug/src/main.o: CC1 := tools/agbcc/bin/agbcc
build/debug/src/main.o: CFLAGS := -g
build/debug/src/main.o: src/main.c FORCE
\t@mkdir -p $(@D)
\t$(C_RECIPE_$(notdir $(CC1)))
build/debug/src/old.o: CC1 := tools/agbcc/bin/old_agbcc
build/debug/src/old.o: CFLAGS := -O1 -g -g
build/debug/src/old.o: src/old.c FORCE
\t@mkdir -p $(@D)
\t$(C_RECIPE_$(notdir $(CC1)))
`,
  });
  assert.equal(modulesMkWriter.scope, 'global');
});

test('a module with a hand-written source (D109): its object built from it by an explicit rule, and SOURCE_<object> for the stale check', () => {
  const model = modelOf(rom, {
    modules: [
      { name: 'main', chunks: [{ name: 'F', items: [dataItem(0x0800_0000, 0x200)] }] },
      { name: 'hand', source: 'src/asm/hand.s', chunks: [{ name: 'G', items: [dataItem(0x0800_0200, 0x200)] }] },
    ],
  });
  assert.equal(
    modulesMkText(model),
    `# modules.mk: the build units in link order and each C unit's compiler, generated by romlift.
OBJS := \\
\tbuild/main.o \\
\tbuild/hand.o
C_OBJS :=
EXPECTED_OBJS := \\
\tbuild/expected/main.o
SOURCE_build/hand.o := src/asm/hand.s
asm/hand.s: ;
build/hand.o: src/asm/hand.s
\t@mkdir -p $(@D)
\t$(AS) $(ASFLAGS) --MD $(@:.o=.d) -o $@ $<
\t@$(call OBJ_SUM,$@,$<) > $(@:.o=.sum)
${debugHead([])}`,
  );
});

test('a tree without C units: C_OBJS is empty, no target-specific line, and make debug links the objects of the build', () => {
  const model = modelOf(rom, {
    modules: [{ name: 'main', chunks: [{ name: 'F', items: [dataItem(0x0800_0000, 0x400)] }] }],
  });
  assert.equal(
    modulesMkText(model),
    `# modules.mk: the build units in link order and each C unit's compiler, generated by romlift.\nOBJS := \\\n\tbuild/main.o\nC_OBJS :=\nEXPECTED_OBJS := \\\n\tbuild/expected/main.o\n${debugHead([])}`,
  );
});

test('in a project: ROMLIFT_TOML_SHA1 records the SHA-1 of romlift.toml the tree comes from, after the comment (fix round 6, correctness-b1-1)', () => {
  const model = modelOf(rom, {
    modules: [{ name: 'main', chunks: [{ name: 'F', items: [dataItem(0x0800_0000, 0x400)] }] }],
  });
  const sha1 = 'ab'.repeat(20);
  assert.equal(
    modulesMkText(model, sha1),
    `# modules.mk: the build units in link order and each C unit's compiler, generated by romlift.\nROMLIFT_TOML_SHA1 := ${sha1}\nOBJS := \\\n\tbuild/main.o\nC_OBJS :=\nEXPECTED_OBJS := \\\n\tbuild/expected/main.o\n${debugHead([])}`,
  );
  const [entry] = [...modulesMkWriter.emit(rom, model, { decomp: { defined: [] }, configSha1: sha1 }, null)];
  assert.ok(entry !== undefined && 'text' in entry && entry.text === modulesMkText(model, sha1));
  const [plain] = [...modulesMkWriter.emit(rom, model, { decomp: { defined: [] } }, null)];
  assert.ok(
    plain !== undefined && 'text' in plain && !plain.text.includes('ROMLIFT_TOML_SHA1'),
    'outside a project, no line',
  );
});

test("through buildModel: the compiler's default flags, then the module's cflags; [build] compiler as the default", () => {
  const analysis = analysisOf(romWith([], { size: 0x200 }), {
    functions: [fact({ entry: BASE + 0x100, end: BASE + 0x110 }), fact({ entry: BASE + 0x110, end: BASE + 0x120 })],
  });
  const config = configOf({
    modules: [
      ['rom_header', BASE],
      { name: 'main', start: HEADER_END, kind: 'c', generated: true },
      { name: 'old', start: BASE + 0x110, kind: 'c', generated: true, compiler: 'old_agbcc', cflags: ['-fno-inline'] },
      { name: 'data', start: BASE + 0x120, kind: 'data', generated: true },
    ],
    functions: [
      [BASE + 0x100, 'A'],
      [BASE + 0x110, 'B'],
    ],
  });
  const model = buildModel(romWith([], { size: 0x200 }), analysis, config);
  const lines = modulesMkText(model).split('\n');
  assert.ok(lines.includes('build/src/main.o: CC1 := tools/agbcc/bin/agbcc'));
  assert.ok(lines.includes('build/src/main.o: CFLAGS := -mthumb-interwork -Wimplicit -Wparentheses -O2 -fhex-asm'));
  assert.ok(lines.includes('build/src/old.o: CC1 := tools/agbcc/bin/old_agbcc'));
  assert.ok(
    lines.includes('build/src/old.o: CFLAGS := -mthumb-interwork -Wimplicit -Wparentheses -O2 -fhex-asm -fno-inline'),
  );
  // g4.multi-compiler reads the lines naming src/<module>.o.
  assert.ok(
    lines
      .filter((l) => l.includes('src/old.o'))
      .join('\n')
      .includes('old_agbcc'),
  );
  assert.ok(lines.some((l) => l.includes('src/main.o') && l.includes('agbcc') && !l.includes('old_agbcc')));
});
